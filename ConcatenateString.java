package concatenatestring;


public class ConcatenateString {

    
    public static void main(String[] args) {
      String name = "Andrie";  
      String color = "red"  ;
      String animal = "dog" ;
      String food = "egg"  ;
      System.out.println("I had a dream that " + name + " ate a ");
      System.out.println(color  + " " + animal + " and said it tasted like " + food + "!");
    }
    
}
